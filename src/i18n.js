/**
 * Перекладає ключ повідомлення в поточну мову з підстановкою параметрів.
 * @param {string} lang - 'uk' | 'en'
 * @param {string} key - ключ повідомлення (наприклад, 'publish.published')
 * @param {Object} [params] - значення для підстановки в {фігурні дужки}
 * @returns {string}
 */
export function t(lang, key, params = {}) {
  const dict = MESSAGES[lang] ?? MESSAGES.uk;
  const template = dict[key] ?? MESSAGES.uk[key] ?? key;
  return template.replace(/{(\w+)}/g, (_, name) => (params[name] !== undefined ? params[name] : `{${name}}`));
}
